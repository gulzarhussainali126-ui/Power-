// ================== QUEUE ==================
function enqueue(jid, task) {
  const prev = chatQueues.get(jid) || Promise.resolve();
  const next = prev.then(task).catch((e) => console.error('Queue error:', e));
  chatQueues.set(jid, next);
  next.finally(() => {
    if (chatQueues.get(jid) === next) chatQueues.delete(jid);
  });
}

// ================== BOT START ==================
async function startBot() {
  const { state, saveCreds } = await useMultiFileAuthState('session_bot');
  const { version, isLatest } = await fetchLatestBaileysVersion();
  console.log(`Using Baileys version ${version.join('.')} (latest: ${isLatest})`);
  pairingRequested = false;

  sock = makeWASocket({
    version,
    auth: state,
    printQRInTerminal: false,
    browser: Browsers.ubuntu('Chrome'),
    logger: pino({ level: 'silent' }),
  });

  sock.ev.on('creds.update', saveCreds);

  sock.ev.on('connection.update', async (update) => {
    const { connection, lastDisconnect, qr } = update;

    if (qr && !sock.authState.creds.registered) {
      console.log(
        'QR LINK:',
        `https://api.qrserver.com/v1/create-qr-code/?size=400x400&data=${encodeURIComponent(qr)}`
      );
      if (!pairingRequested) {
        pairingRequested = true;
        setTimeout(async () => {
          try {
            const code = await sock.requestPairingCode(BUSINESS.botNumber);
            console.log('PAIRING CODE:', code);
          } catch (e) {
            console.error('Pairing code error:', e.message);
          }
        }, 1000);
      }
    }

    if (connection === 'open') {
      console.log('✅ Bot is live');
    }

    if (connection === 'close') {
      const statusCode = lastDisconnect?.error?.output?.statusCode;
      if (statusCode === DisconnectReason.loggedOut) {
        console.log('Logged out. Deleting session and restarting...');
        deleteSession();
        startBot();
      } else {
        console.log('Connection closed. Reconnecting in 4s...');
        setTimeout(startBot, 4000);
      }
    }
  });

  sock.ev.on('messages.upsert', async ({ messages, type }) => {
    if (type !== 'notify') return;
    for (const msg of messages) {
      if (!msg?.message) continue;
      if (msg.key.fromMe) continue;
      const jid = msg.key.remoteJidAlt || msg.key.remoteJid;
      if (!jid) continue;
      if (jid.endsWith('@g.us') || jid === 'status@broadcast' || jid.endsWith('@newsletter')) continue;
      const id = msg.key.id;
      if (!id) continue;
      if (processedMessages.has(id)) continue;
      processedMessages.add(id);
      if (processedMessages.size > 500) {
        const first = processedMessages.values().next().value;
        processedMessages.delete(first);
      }
      enqueue(jid, () => handleMessage(msg, jid));
    }
  });
}

function deleteSession() {
  try {
    fs.rmSync(path.join(process.cwd(), 'session_bot'), { recursive: true, force: true });
    console.log('Session deleted.');
  } catch (e) {
    console.error('Delete session error:', e.message);
  }
}

// ================== START ==================
console.log('Starting WhatsApp AI agent...');
startBot().catch((e) => {
  console.error('Fatal start error:', e);
  process.exit(1);
});

