// ================== GROQ ==================
const GROQ_URL = 'https://api.groq.com/openai/v1/chat/completions';
const GROQ_MODEL = 'llama-3.3-70b-versatile';
const GROQ_API_KEY = process.env.GROQ_API_KEY || '';

if (!GROQ_API_KEY) {
  console.warn('⚠️ GROQ_API_KEY is not set. Bot will use fallback fixed replies.');
}

// ================== GLOBALS ==================
let sock;
let pairingRequested = false;
const chatStates = new Map();
const historyMap = new Map();
const processedMessages = new Set();
const chatQueues = new Map();

// ================== GROQ HELPERS ==================
async function groqChat(messages, { maxTokens = 200, temperature = 0.7 } = {}) {
  if (!GROQ_API_KEY) return null;
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 15000);
  try {
    const res = await fetch(GROQ_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${GROQ_API_KEY}`,
      },
      body: JSON.stringify({
        model: GROQ_MODEL,
        messages,
        max_tokens: maxTokens,
        temperature,
      }),
      signal: controller.signal,
    });
    clearTimeout(timeout);
    if (!res.ok) {
      const err = await res.text();
      console.error('Groq API error:', res.status, err.slice(0, 200));
      return null;
    }
    const data = await res.json();
    return data.choices?.[0]?.message?.content?.trim() || null;
  } catch (e) {
    clearTimeout(timeout);
    console.error('Groq fetch error:', e.message);
    return null;
  }
}

async function humanize(jid, instruction, fallback) {
  const history = getHistory(jid);
  const sys = `You are a warm, friendly WhatsApp assistant for ${BUSINESS.name}. ${BUSINESS.extraRules || ''} ${instruction} Keep replies short (1-2 lines), use 0-2 emojis, and never invent prices or items.`;
  const msgs = [
    { role: 'system', content: sys },
    ...history.slice(-6),
  ];
  const reply = await groqChat(msgs, { maxTokens: 120, temperature: 0.8 });
  return reply || fallback;
}

async function generalReply(jid, stepContext) {
  const history = getHistory(jid);
  const sys = `You are a helpful, friendly assistant for ${BUSINESS.name} in ${BUSINESS.city}. Phone: ${BUSINESS.phone}. Hours: ${BUSINESS.hours}. Flow: ${BUSINESS.flow}. ${BUSINESS.extraRules || ''} Answer briefly (max 3 lines), use emojis sparingly. If the customer wants to order, tell them to reply MENU. Current step: ${stepContext}.`;
  const msgs = [{ role: 'system', content: sys }, ...history.slice(-8)];
  return await groqChat(msgs, { maxTokens: 200, temperature: 0.8 });
}

// ================== HISTORY ==================
function pushHistory(jid, role, content) {
  if (!historyMap.has(jid)) historyMap.set(jid, []);
  const arr = historyMap.get(jid);
  arr.push({ role, content });
  if (arr.length > 12) arr.splice(0, arr.length - 12);
}
function getHistory(jid) {
  return [...(historyMap.get(jid) || [])];
}
function clearHistory(jid) {
  historyMap.delete(jid);
}

// ================== STATE ==================
function getState(jid) {
  if (!chatStates.has(jid)) {
    chatStates.set(jid, {
      step: 'NEW',
      cart: {},
      paymentMethod: '',
      address: '',
      service: '',
      datetime: '',
      name: '',
    });
  }
  return chatStates.get(jid);
}
function resetState(jid, keepHistory = false) {
  chatStates.set(jid, {
    step: 'NEW',
    cart: {},
    paymentMethod: '',
    address: '',
    service: '',
    datetime: '',
    name: '',
  });
  if (!keepHistory) clearHistory(jid);
}

// ================== SEND ==================
async function send(jid, text) {
  if (!sock) {
    console.error('Cannot send: sock is not ready');
    return;
  }
  try {
    await sock.sendMessage(jid, { text });
    pushHistory(jid, 'assistant', text);
    console.log(`📤 Sent to ${jid}: ${text.slice(0, 80)}...`);
  } catch (e) {
    console.error('Send error:', e.message);
  }
}

// ================== CART HELPERS ==================
function isValidItem(id) {
  return id >= 1 && id <= BUSINESS.menu.length;
}
function parseItems(text) {
  if (!text) return [];
  const parts = text.split(',').map((p) => p.trim()).filter(Boolean);
  const items = [];
  for (const part of parts) {
    const qtyMatch = part.match(/(\d+)\s*[xX*]\s*(\d+)/);
    if (qtyMatch) {
      const id = parseInt(qtyMatch[1], 10);
      const qty = parseInt(qtyMatch[2], 10);
      if (isValidItem(id) && qty > 0) items.push({ id, qty });
      continue;
    }
    const numMatch = part.match(/(\d+)/);
    if (numMatch) {
      const id = parseInt(numMatch[1], 10);
      if (isValidItem(id)) items.push({ id, qty: 1 });
    }
  }
  return items;
}
function addToCart(state, items) {
  items.forEach(({ id, qty }) => {
    state.cart[id] = (state.cart[id] || 0) + qty;
  });
}
function buildCartSummary(cart) {
  let subtotal = 0;
  let lines = '';
  Object.entries(cart).forEach(([id, qty]) => {
    const item = BUSINESS.menu[parseInt(id, 10) - 1];
    if (!item) return;
    const lineTotal = item.price * qty;
    subtotal += lineTotal;
    lines += `• ${qty}x ${item.name} — Rs ${lineTotal}\n`;
  });
  const delivery = BUSINESS.deliveryFee;
  const total = subtotal + delivery;
  return `🛒 *Your cart*\n${lines}\nSubtotal: Rs ${subtotal}\nDelivery: Rs ${delivery}\n*Total: Rs ${total}*`;
}
function formatMenu() {
  let s = `📋 *${BUSINESS.name} Menu*\n\n`;
  BUSINESS.menu.forEach((item, idx) => {
    s += `${idx + 1}. ${item.name} — Rs ${item.price}\n`;
  });
  s += `\nReply with item numbers like 1x2, 5, 9.`;
  return s;
}
function formatServices() {
  let s = `📋 *Our services*\n\n`;
  BUSINESS.menu.forEach((item, idx) => {
    s += `${idx + 1}. ${item.name} — Rs ${item.price}\n`;
  });
  s += `\nReply with the service number to book.`;
  return s;
}
function generateOrderId() {
  return `ORD-${Date.now().toString().slice(-6)}${Math.random().toString(36).slice(2, 4).toUpperCase()}`;
}
function generateBookingId() {
  return `BK-${Date.now().toString().slice(-6)}${Math.random().toString(36).slice(2, 4).toUpperCase()}`;
}

// ================== MESSAGE HANDLING ==================
function getText(msg) {
  const m = msg.message;
  if (!m) return '';
  return (m.conversation || m.extendedTextMessage?.text || m.imageMessage?.caption || '').trim();
}

async function handleMessage(msg, jid) {
  try {
    const text = getText(msg);
    const hasImage = !!msg.message?.imageMessage;
    if (!text && !hasImage) return;

    pushHistory(jid, 'user', text || '[image]');
    const state = getState(jid);
    const lower = text.toLowerCase();

    // Global cancel
    if (lower === '0' || lower === 'cancel') {
      resetState(jid);
      const reply = await humanize(
        jid,
        'Customer cancelled the flow. Generate a short cancellation confirmation.',
        'Cancelled. Reply MENU to start again. 😊'
      );
      await send(jid, reply);
      return;
    }

    switch (state.step) {
      case 'NEW':
        await handleNew(jid, text);
        break;
      case 'AWAIT_MENU':
        await handleAwaitMenu(jid, text);
        break;
      case 'ORDERING':
        await handleOrdering(jid, text);
        break;
      case 'CART_CONFIRM':
        await handleCartConfirm(jid, text);
        break;
      case 'PAYMENT':
        await handlePayment(jid, text);
        break;
      case 'PAYMENT_CONFIRM':
        await handlePaymentConfirm(jid, text, hasImage);
        break;
      case 'ADDRESS':
        await handleAddress(jid, text);
        break;
      case 'BOOKING_SERVICE':
        await handleBookingService(jid, text);
        break;
      case 'BOOKING_DATETIME':
        await handleBookingDatetime(jid, text);
        break;
      case 'BOOKING_NAME':
        await handleBookingName(jid, text);
        break;
      default:
        resetState(jid);
        const fallback = await generalReply(jid, 'UNKNOWN');
        await send(jid, fallback || 'Reply MENU to start. 😊');
    }
  } catch (e) {
    console.error('handleMessage error:', e);
    try {
      await send(jid, 'Sorry, something went wrong. Reply MENU to restart. 😊');
    } catch (_) {}
  }
}

// ---------- ORDER FLOW ----------
async function handleNew(jid, text) {
  const state = getState(jid);

  if (BUSINESS.flow === 'INFO_ONLY') {
    const reply = await generalReply(jid, 'INFO_ONLY');
    await send(jid, reply || `Hi! Ask me anything about ${BUSINESS.name}. 😊`);
    return;
  }

  if (BUSINESS.flow === 'BOOKING') {
    const greeting = await humanize(
      jid,
      'Generate a warm welcome for a booking customer. Keep it short.',
      'Hello! 👋'
    );
    const welcome = `${greeting}\n\n🏪 ${BUSINESS.name}\n📞 ${BUSINESS.phone}\n🕒 ${BUSINESS.hours}\n\n${formatServices()}`;
    await send(jid, welcome);
    state.step = 'BOOKING_SERVICE';
    return;
  }

  // ORDER flow
  const greeting = await humanize(
    jid,
    'Generate a warm welcome message. Keep it short.',
    'Hello! 👋'
  );
  const welcome = `${greeting}\n\n🏪 ${BUSINESS.name}\n📞 Call ${BUSINESS.phone}\n🕒 ${BUSINESS.hours}\n\nReply 1 or MENU to see the menu.`;
  await send(jid, welcome);
  state.step = 'AWAIT_MENU';
}

async function handleAwaitMenu(jid, text) {
  const state = getState(jid);
  const lower = text.toLowerCase();

  if (lower === '1' || lower.includes('menu')) {
    await send(jid, formatMenu());
    state.step = 'ORDERING';
    return;
  }

  const items = parseItems(text);
  if (items.length) {
    state.cart = {};
    addToCart(state, items);
    const summary = buildCartSummary(state.cart);
    const intro = await humanize(jid, 'Customer ordered directly. Generate a short friendly line.', 'Added! 🛒');
    await send(jid, `${intro}\n\n${summary}\n\nReply YES to confirm, ADD MORE to add more, or CANCEL to cancel.`);
    state.step = 'CART_CONFIRM';
    return;
  }

  const help = await humanize(
    jid,
    'Customer is at the menu step but did not send a valid menu command. Ask them to reply 1 or MENU.',
    'Reply 1 or MENU to see the menu. 😊'
  );
  await send(jid, help);
}

async function handleOrdering(jid, text) {
  const state = getState(jid);
  const items = parseItems(text);

  if (items.length) {
    addToCart(state, items);
    const summary = buildCartSummary(state.cart);
    const intro = await humanize(jid, 'Customer added items. Generate a short friendly line.', 'Got it! 🛒');
    await send(jid, `${intro}\n\n${summary}\n\nReply YES to confirm, ADD MORE to add more, or CANCEL to cancel.`);
    state.step = 'CART_CONFIRM';
  } else {
    const help = await humanize(
      jid,
      'Customer is ordering but sent invalid items. Ask them to send item numbers like 1x2, 5, 9.',
      'Please send item numbers like 1x2, 5, 9. 😊'
    );
    await send(jid, help);
  }
}

async function handleCartConfirm(jid, text) {
  const state = getState(jid);
  const lower = text.toLowerCase();

  if (['yes', 'confirm', 'ok', 'y'].includes(lower)) {
    const intro = await humanize(jid, 'Customer confirmed cart. Generate a short line.', 'Great! ✅');
    const paymentText = `💳 *Payment options*\n1. Cash on delivery\n2. Online (JazzCash/EasyPaisa)\n\nReply 1 for cash or 2 for online.`;
    await send(jid, `${intro}\n\n${paymentText}`);
    state.step = 'PAYMENT';
    return;
  }

  if (lower.includes('add') || lower.includes('more')) {
    const ask = await humanize(jid, 'Customer wants to add more items. Ask them to send more item numbers.', 'Send more item numbers. 🛒');
    await send(jid, ask);
    state.step = 'ORDERING';
    return;
  }

  const help = await humanize(
    jid,
    'Customer is at cart confirmation but sent an invalid reply. Ask them to reply YES, ADD MORE, or CANCEL.',
    'Reply YES to confirm, ADD MORE, or CANCEL. 😊'
  );
  await send(jid, help);
}

async function handlePayment(jid, text) {
  const state = getState(jid);
  const lower = text.toLowerCase();

  if (lower === '1' || lower.includes('cash')) {
    state.paymentMethod = 'Cash on delivery';
    const ask = await humanize(jid, 'Customer chose cash on delivery. Ask for the full delivery address.', 'Please send your full delivery address. 📍');
    await send(jid, ask);
    state.step = 'ADDRESS';
    return;
  }

  if (lower === '2' || lower.includes('online') || lower.includes('jazz') || lower.includes('easy')) {
    state.paymentMethod = 'Online';
    const intro = await humanize(jid, 'Customer chose online payment. Generate a short line.', 'Please send the payment. 💸');
    const details = `Send to:\n${BUSINESS.paymentMethods}\nAccount: ${BUSINESS.paymentAccount}\n\nAfter paying, send a screenshot or reply PAID.`;
    await send(jid, `${intro}\n\n${details}`);
    state.step = 'PAYMENT_CONFIRM';
    return;
  }

  const help = await humanize(
    jid,
    'Customer is at payment step but sent an invalid reply. Ask them to reply 1 for cash or 2 for online.',
    'Reply 1 for cash or 2 for online. 😊'
  );
  await send(jid, help);
}

async function handlePaymentConfirm(jid, text, hasImage) {
  const state = getState(jid);
  const lower = text.toLowerCase();

  if (hasImage || lower.includes('paid') || lower.includes('screenshot')) {
    const ask = await humanize(jid, 'Payment confirmed. Ask for the full delivery address.', 'Payment received! ✅ Please send your full delivery address. 📍');
    await send(jid, ask);
    state.step = 'ADDRESS';
    return;
  }

  const help = await humanize(
    jid,
    'Customer is at payment confirmation but did not confirm. Ask them to send the screenshot or reply PAID.',
    'Please send the payment screenshot or reply PAID. 😊'
  );
  await send(jid, help);
}

async function handleAddress(jid, text) {
  const state = getState(jid);
  state.address = text;
  const orderId = generateOrderId();
  const summary = buildCartSummary(state.cart);
  const intro = await humanize(jid, 'Order is complete. Generate a warm confirmation line.', 'Thank you! 🎉');
  const confirmation = `✅ *Order confirmed!*\n\n🆔 ${orderId}\n\n${summary}\n\n📍 Deliver to: ${state.address}\n💳 Payment: ${state.paymentMethod}\n⏱️ Your order will reach you in ${BUSINESS.deliveryTime}.`;
  await send(jid, `${intro}\n\n${confirmation}`);

  if (BUSINESS.ownerNumber) {
    const ownerJid = `${BUSINESS.ownerNumber.replace(/\D/g, '')}@s.whatsapp.net`;
    const ownerMsg = `🆕 *New order* ${orderId}\nCustomer: ${jid}\n\n${summary}\n\n📍 ${state.address}\n💳 ${state.paymentMethod}`;
    await send(ownerJid, ownerMsg);
  }

  resetState(jid, true);
}

